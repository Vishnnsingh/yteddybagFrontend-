import React, { useEffect } from 'react';
import { useHeaderNavigation } from '../../Context/HeaderNavigationContext';

const PrivacyPolicy: React.FC = () => {
  const { sitePages, pagesLoading, refreshSitePages } = useHeaderNavigation();
  const pageData = sitePages['privacy-policy'] || {
    title: 'Privacy Policy',
    description: `We value the trust you place in us and recognize the importance of secure transactions and information privacy. This Privacy Policy describes how YTeddybags collects, uses, shares or otherwise processes your personal information through YTeddybags website and its mobile application.\n\n1. Collection of Your Information:\nWhen You use our Platform, We collect and store your information which is provided by you from time to time. In general, you can browse the Platform without telling us who you are or revealing any personal information about yourself. Once you give us your personal information, you are not anonymous to us.\n\n2. Use of Demographic and Profile Data:\nWe use personal information to provide the services you request. To the extent we use your personal information to market to you, we will provide you the ability to opt-out of such uses. We use your personal information to assist sellers in handling and fulfilling orders, enhance customer experience, and resolve disputes.\n\n3. Cookies:\nWe use data collection devices such as 'cookies' on certain pages of the Platform to help analyze our web page flow, measure promotional effectiveness, and promote trust and safety. Cookies do not contain any of your personal information.\n\n4. Security Precautions:\nWe maintain reasonable physical, electronic and procedural safeguards to protect your information. Whenever you access your account information, we offer the use of a secure server. Once your information is in our possession, we adhere to strict security guidelines protecting it against unauthorized access.`,
    updated_at: new Date().toISOString(),
  };

  useEffect(() => {
    window.scrollTo({ top: 0, behavior: 'instant' });
    refreshSitePages();
    document.title = `YTEDDYBAGS: ${pageData.title ? pageData.title.toUpperCase() : 'PRIVACY POLICY'}`;
  }, [pageData.title, refreshSitePages]);

  const rawDescription = pageData.description || '';
  const paragraphs = rawDescription.split('\n\n').filter((p) => p.trim().length > 0);

  const displayTitle = pageData.title
    ? pageData.title.toUpperCase().startsWith('YTEDDYBAGS')
      ? pageData.title.toUpperCase()
      : `YTEDDYBAGS: ${pageData.title.toUpperCase()}`
    : 'YTEDDYBAGS: PRIVACY POLICY';

  return (
    <div className="bg-white min-h-screen text-[#282C3F] py-8 sm:py-12 px-4 sm:px-8 lg:px-12 font-sans">
      <div className="max-w-4xl mx-auto">
        {/* Language selector & top bar (Exact Myntra aesthetic) */}
        <div className="flex justify-end mb-6">
          <div className="inline-flex items-center gap-1.5 px-3 py-1 border border-gray-300 rounded text-xs text-[#282C3F] font-medium bg-white shadow-2xs">
            <svg className="w-3.5 h-3.5 text-[#535766]" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M3 5h12M9 3v2m1.048 9.5A18.022 18.022 0 016.412 9m6.088 9h7M11 21l5-10 5 10M12.751 5C11.783 10.77 8.07 15.61 3 18.129" />
            </svg>
            <span>English</span>
            <span className="text-[10px] text-gray-500">▼</span>
          </div>
        </div>

        {/* Centered Main Title */}
        <h1 className="text-lg sm:text-xl font-bold text-[#282C3F] tracking-wide text-center uppercase mb-8">
          {displayTitle}
        </h1>

        {/* Disclaimer */}
        <div className="mb-6">
          <h4 className="font-bold text-xs sm:text-[13px] text-[#282C3F] mb-1">Disclaimer</h4>
          <p className="text-xs sm:text-[12px] text-[#696E79] leading-relaxed">
            The translations provided are generated by AI; in case of any discrepancy or difference, the English version will take precedence over the translation.
          </p>
        </div>

        {/* Main Content Body */}
        {pagesLoading && paragraphs.length === 0 ? (
          <div className="space-y-4 py-8">
            <div className="h-4 bg-gray-100 rounded w-full animate-pulse" />
            <div className="h-4 bg-gray-100 rounded w-5/6 animate-pulse" />
            <div className="h-4 bg-gray-100 rounded w-4/5 animate-pulse" />
            <div className="h-4 bg-gray-100 rounded w-full animate-pulse" />
          </div>
        ) : (
          <div className="text-xs sm:text-[13px] text-[#3E4152] leading-relaxed space-y-4">
            {paragraphs.map((p, idx) => {
              const trimmed = p.trim();
              const match = trimmed.match(/^([0-9]+\.\s+[^:\n]+:?)([\s\S]*)$/);
              if (match) {
                const heading = match[1];
                const rest = match[2];
                return (
                  <div key={idx} className="pt-2">
                    <h2 className="font-bold text-xs sm:text-[13.5px] text-[#282C3F] mb-1">
                      {heading}
                    </h2>
                    {rest.trim() && (
                      <p className="text-xs sm:text-[13px] text-[#3E4152] leading-relaxed whitespace-pre-line">
                        {rest.trim()}
                      </p>
                    )}
                  </div>
                );
              }
              return (
                <p key={idx} className="whitespace-pre-line text-xs sm:text-[13px] text-[#3E4152] leading-relaxed">
                  {trimmed}
                </p>
              );
            })}
          </div>
        )}
      </div>
    </div>
  );
};

export default PrivacyPolicy;
